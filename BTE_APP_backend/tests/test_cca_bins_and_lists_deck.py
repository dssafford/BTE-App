def test_prompts_distinct():
    prompts = [_normalize(c["prompt"]) for c in load()["cards"]]
    assert len(set(prompts)) == len(prompts)


def test_answer_position_is_not_a_tell():
    slots = Counter(
        c["metadata"]["choices"].index(c["answer"]) for c in load()["cards"]
    )
    assert set(slots) == {0, 1, 2, 3}
    assert min(slots.values()) >= TOTAL / 8, "position spread skewed: %s" % dict(slots)


def test_answer_length_is_not_a_tell():
    """Only a STRICTLY longest answer leaks.

    This deck deliberately fields options that tie on length — permutations of
    an ordered roster, and count cards whose options are all single digits.
    A tie carries no signal a test-taker could act on, so the sibling decks'
    ties-included measure would flag ~24% of cards for a tell that does not
    exist. Strictly-longest is the honest measure here.
    """
    cards = load()["cards"]
    strictly_longest = sum(
        1 for c in cards
        if all(len(c["answer"]) > len(x)
               for x in c["metadata"]["choices"] if x != c["answer"])
    )
    assert strictly_longest <= len(cards) / 4, (
        "longest-option heuristic scores %d/%d" % (strictly_longest, len(cards))
    )


def test_no_prompt_overlap_with_existing_decks():
    existing = set()
    for name in SIBLING_DECKS:
        for card in load(name)["cards"]:
            existing.add(_normalize(card["prompt"].rpartition("\n\n")[2]))
    for card in load()["cards"]:
        assert _normalize(card["prompt"]) not in existing, card["prompt"]
